"""Урок 4. Матрица проверки цитат: где порог спасает, а где нет.

Запуск:  python3 examples/04_cite_matrix.py

Один источник, дюжина вариантов цитаты. Смотрите на колонку «похожесть»:
подмена одной цифры даёт 0.97 — выше любого разумного порога. Поэтому
проверка идёт в два уровня: похожесть текста И совпадение чисел.
"""

from __future__ import annotations

from _mock import banner

from sci_harness.provenance import find_quote, numbers

SOURCE = """Таблица 2. Энергопотребление
В простое процессор потребляет 6 Вт. Под нагрузкой — 88 Вт.
Температура не превышает 78 °C. Замеры: ваттметр, шаг 1 с, 3 повтора."""

VARIANTS: list[tuple[str, str]] = [
    ("дословно", "В простое процессор потребляет 6 Вт"),
    ("другая типографика", "В простое процессор потребляет 6\u00a0Вт"),
    ("дефис вместо тире", "Под нагрузкой - 88 Вт"),
    ("подмена цифры 88→98", "Под нагрузкой — 98 Вт"),
    ("подмена цифры 6→60", "В простое процессор потребляет 60 Вт"),
    ("лишнее слово", "В простое процессор потребляет примерно 6 Вт"),
    ("перестановка слов", "78 °C — предел температуры"),
    ("выдумка", "Процессор работает на 3 нм техпроцессе"),
]

banner(f"Источник: {len(SOURCE)} символов, числа: {numbers(SOURCE)}")
print(f"\n{'вариант':<24} {'похож.':>7} {'итог':>6}  причина")

for label, quote in VARIANTS:
    match = find_quote(quote, SOURCE)
    verdict = "ПРИНЯТ" if match.found else "отказ"
    print(f"{label:<24} {match.score:>7.2f} {verdict:>6}  {match.reason}")

banner("Почему «лишнее слово» проваливается, а перестановка — тоже")
print("Проверка требует согласия по числам: в цитате [6], в источнике")
print("на этом месте [6] — совпало. Но текст должен ещё и совпасть")
print("достаточно точно. Там, где модель пересказывает своими словами,")
print("она должна либо цитировать, либо честно писать «по данным обзора»")
print("и надеяться на редактора — но не на инструмент.")

banner("Практическое правило для статьи")
print("1. Каждое число — с локатором (страница, таблица, раздел).")
print("2. Порог 0.92 пропускает пунктуацию, но не цифры и не смысл.")
print("3. Счётчик unsourced_share идёт в отчёт прогона, а не «в стол».")
